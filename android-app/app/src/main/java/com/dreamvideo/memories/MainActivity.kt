private val Night = Color(0xFF09070F)
private val Panel = Color(0xFF191323)
private val Purple = Color(0xFF9B70E8)
private val Gold = Color(0xFFE7C477)

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent { DreamApp() }
    }
}

@Composable
fun DreamApp() {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var endpoint by remember { mutableStateOf("https://YOUR-WORKER.workers.dev") }
    var prompt by remember { mutableStateOf("") }
    var status by remember { mutableStateOf("Connect your Cloudflare Worker to begin.") }
    var busy by remember { mutableStateOf(false) }
    var selectedBytes by remember { mutableStateOf<ByteArray?>(null) }
    var generated by remember { mutableStateOf<android.graphics.Bitmap?>(null) }
    val picker = rememberLauncherForActivityResult(ActivityResultContracts.GetContent()) { uri ->
        if (uri != null) selectedBytes = context.contentResolver.openInputStream(uri)?.use { it.readBytes() }
    }

    MaterialTheme(colorScheme = darkColorScheme(
        background = Night, surface = Panel, primary = Purple, secondary = Gold,
        onBackground = Color.White, onSurface = Color.White
    )) {
        Column(Modifier.fillMaxSize().background(Night).verticalScroll(rememberScrollState()).padding(20.dp)) {
            Text("DREAM VIDEO", color = Gold, fontSize = 13.sp, fontWeight = FontWeight.Bold, letterSpacing = 3.sp)
            Text("AI MEMORIES", color = Color.White, fontSize = 30.sp, fontWeight = FontWeight.ExtraBold)
            Text("Create images from imagination.", color = Purple, fontSize = 14.sp)
            Spacer(Modifier.height(22.dp))
            Card(colors = CardDefaults.cardColors(containerColor = Panel), shape = RoundedCornerShape(22.dp)) {
                Column(Modifier.padding(16.dp)) {
                    Text("CLOUD CONNECTION", color = Gold, fontWeight = FontWeight.Bold)
                    Spacer(Modifier.height(8.dp))
                    OutlinedTextField(endpoint, { endpoint = it }, label = { Text("Cloudflare Worker URL") }, singleLine = true, modifier = Modifier.fillMaxWidth())
                    Spacer(Modifier.height(18.dp))
                    Text("YOUR PROMPT", color = Gold, fontWeight = FontWeight.Bold)
                    Spacer(Modifier.height(8.dp))
                    OutlinedTextField(prompt, { prompt = it }, placeholder = { Text("Describe the image you dream of...") }, minLines = 4, modifier = Modifier.fillMaxWidth())
                    Spacer(Modifier.height(12.dp))
                    OutlinedButton(onClick = { picker.launch("image/*") }, modifier = Modifier.fillMaxWidth()) {
                        Text(if (selectedBytes == null) "Choose photo for image-to-image" else "Source photo selected")
                    }
                    Spacer(Modifier.height(14.dp))
                    Button(
                        onClick = {
                            if (prompt.isBlank() || endpoint.contains("YOUR-WORKER")) {
                                status = "Enter a prompt and your deployed Worker URL."
                            } else {
                                busy = true; status = "Sending request securely…"
                                scope.launch {
                                    try {
                                        val result = withContext(Dispatchers.IO) {
                                            val url = endpoint.trimEnd('/') + if (selectedBytes == null) "/generate" else "/edit"
                                            val conn = (URL(url).openConnection() as HttpURLConnection)
                                            conn.requestMethod = "POST"; conn.connectTimeout = 30000; conn.readTimeout = 120000
                                            conn.doOutput = true; conn.setRequestProperty("Content-Type", "application/json")
                                            val body = JSONObject().put("prompt", prompt)
                                            if (selectedBytes != null) body.put("image_base64", android.util.Base64.encodeToString(selectedBytes, android.util.Base64.NO_WRAP))
                                            conn.outputStream.use { it.write(body.toString().toByteArray()) }
                                            val stream = if (conn.responseCode in 200..299) conn.inputStream else conn.errorStream
                                            val bytes = stream.use { it.readBytes() }
                                            if (conn.responseCode !in 200..299) throw Exception(String(bytes).take(500))
                                            bytes
                                        }
                                        generated = BitmapFactory.decodeByteArray(result, 0, result.size)
                                        status = if (generated != null) "Image created. Save it to your gallery." else "The service returned an unsupported image format."
                                    } catch (e: Exception) { status = "Request failed: ${e.message}" }
                                    finally { busy = false }
                                }
                            }
                        },
                        enabled = !busy,
                        modifier = Modifier.fillMaxWidth(),
                        colors = ButtonDefaults.buttonColors(containerColor = Purple)
                    ) { Text(if (busy) "CREATING…" else if (selectedBytes == null) "GENERATE IMAGE" else "TRANSFORM IMAGE", fontWeight = FontWeight.Bold) }
                }
            }
            Spacer(Modifier.height(16.dp))
            if (generated != null) {
                Image(generated!!.asImageBitmap(), null, Modifier.fillMaxWidth().heightIn(max = 420.dp))
                Spacer(Modifier.height(8.dp))
                Button(onClick = {
                    val values = ContentValues().apply { put(MediaStore.Images.Media.DISPLAY_NAME, "DreamMemory_${System.currentTimeMillis()}.png"); put(MediaStore.Images.Media.MIME_TYPE, "image/png"); put(MediaStore.Images.Media.RELATIVE_PATH, "Pictures/DreamVideoAIMemories") }
                    val uri = context.contentResolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, values)
                    uri?.let { context.contentResolver.openOutputStream(it)?.use { out -> generated!!.compress(android.graphics.Bitmap.CompressFormat.PNG, 100, out) } }
                    status = if (uri != null) "Saved to Pictures/DreamVideoAIMemories" else "Could not save image."
                }, modifier = Modifier.fillMaxWidth()) { Text("SAVE TO GALLERY") }
            }
            Spacer(Modifier.height(14.dp))
            Text(status, color = Gold, fontSize = 13.sp)
            Spacer(Modifier.height(20.dp))
            Text("Your images are processed by the cloud service you configure. Do not upload photos without permission from the people shown.", color = Color.LightGray, fontSize = 11.sp)
        }
    }
}
